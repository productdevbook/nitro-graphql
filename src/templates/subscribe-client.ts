/**
 * Create a GraphQL subscription using Server-Sent Events (SSE)
 * Compatible with GraphQL Yoga's SSE subscription mode
 */
export function createSSESubscription<TData = unknown, TVariables = Record<string, unknown>>(
  endpoint: string,
  options: SubscriptionOptions<TVariables>,
): SubscriptionClient {
  let eventSource: EventSource | null = null
  let isConnected = false
  let retryCount = 0
  const maxRetries = options.maxRetries ?? 5

  function connect() {
    if (typeof window === 'undefined') {
      // SSR - don't connect
      return
    }

    // Build URL with query parameters
    const url = new URL(endpoint, window.location.origin)
    url.searchParams.set('query', options.query)
    if (options.variables) {
      url.searchParams.set('variables', JSON.stringify(options.variables))
    }

    // Close existing connection
    disconnect()

    eventSource = new EventSource(url.toString())

    eventSource.onopen = () => {
      isConnected = true
      retryCount = 0
      options.onConnected?.()
    }

    // GraphQL Yoga sends 'next' events for subscription data
    eventSource.addEventListener('next', (event: MessageEvent) => {
      try {
        const response = JSON.parse(event.data)
        if (response.errors) {
          options.onError?.(new Error(response.errors[0]?.message || 'GraphQL Error'))
        } else if (response.data) {
          // Extract first field from data (the subscription field)
          const subscriptionData = Object.values(response.data)[0]
          options.onData?.(subscriptionData as TData)
        }
      } catch (e) {
        options.onError?.(e instanceof Error ? e : new Error('Failed to parse subscription data'))
      }
    })

    // Also handle generic message event
    eventSource.onmessage = (event) => {
      try {
        const response = JSON.parse(event.data)
        if (response.data) {
          const subscriptionData = Object.values(response.data)[0]
          options.onData?.(subscriptionData as TData)
        }
      } catch {
        // Ignore parse errors for non-JSON messages
      }
    }

    eventSource.onerror = () => {
      isConnected = false
      options.onDisconnected?.()

      // Reconnect with exponential backoff
      if (retryCount < maxRetries) {
        retryCount++
        const delay = Math.min(1000 * Math.pow(2, retryCount), 30000)
        setTimeout(connect, delay)
      } else {
        options.onError?.(new Error('Max reconnection attempts reached'))
      }
    }
  }

  function disconnect() {
    if (eventSource) {
      eventSource.close()
      eventSource = null
      isConnected = false
    }
  }

  // Start connection
  connect()

  return {
    unsubscribe: disconnect,
    get isConnected() {
      return isConnected
    },
  }
}

